const guideBySlug = new Map(helpGuides.map((guide) => [guide.slug, guide]));

export function getHelpGuide(slug: string): HelpGuide | undefined {
  return guideBySlug.get(slug);
}

export function helpGuidesByCategory(category: HelpCategoryId): HelpGuide[] {
  return helpGuides.filter((guide) => guide.category === category);
}

export function popularHelpGuides(): HelpGuide[] {
  return helpGuides.filter((guide) => guide.popular);
}

export function relatedHelpGuides(guide: HelpGuide): HelpGuide[] {
  return guide.related
    .map((slug) => guideBySlug.get(slug))
    .filter((item): item is HelpGuide => Boolean(item));
}

function guideSearchText(guide: HelpGuide): string {
  const parts = [guide.title, guide.description];
  for (const section of guide.sections) {
    parts.push(section.title);
    for (const block of section.blocks) {
      if (block.type === "p" || block.type === "callout") parts.push(block.text);
      if (block.type === "ul" || block.type === "ol") parts.push(...block.items);
      if (block.type === "steps") {
        for (const item of block.items) {
          parts.push(item.title, item.text);
        }
      }
      if (block.type === "table") {
        parts.push(...block.headers, ...block.rows.flat());
      }
      if (block.type === "faq") {
        for (const item of block.items) {
          parts.push(item.q, item.a);
        }
      }
      if (block.type === "cta") parts.push(block.label, block.hint ?? "");
    }
  }
  return parts.join(" ").toLowerCase();
}

export function searchHelpGuides(query: string): HelpGuide[] {
  const q = query.trim().toLowerCase();
  if (!q) return helpGuides;
  return helpGuides.filter((guide) => guideSearchText(guide).includes(q));
}
